// Generates the PWA's static files into public/ (committed; no network, no new dependency):
//   icons (any/maskable/apple-touch, favicon), the offline page and its stylesheet, and font copies.
// Usage (from frontend/): npm run pwa:assets   (runs this file through tsx; sharp is the one Next ships and is only needed here)
// Colours come from app/styles/tokens.css (the Light theme's --accent/--on-accent), never typed here.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { themeInitScript } from "../lib/theme.ts";
import { MANIFEST_THEME_COLOR } from "../lib/pwa-colors.ts";

const root = (path) => fileURLToPath(new URL(`../${path}`, import.meta.url));
const require = createRequire(import.meta.url);
const sharp = require("sharp");

const tokens = readFileSync(root("app/styles/tokens.css"), "utf8");
const light = /html\[data-theme="light"\][^{]*\{([^}]*)\}/.exec(tokens)[1];
const token = (name) => new RegExp(`${name}:\\s*(#[0-9a-fA-F]{6})`).exec(light)[1];
const accent = token("--accent");
const onAccent = token("--on-accent");

// The brand mark is an "h" in a rounded tile. The glyph is drawn as a stroked path so no font is needed.
const glyph = (scale = 1) => `<g transform="translate(256 256) scale(${scale}) translate(-256 -256)" fill="none" stroke="${onAccent}" stroke-width="56" stroke-linecap="round" stroke-linejoin="round"><path d="M176 112V400M176 276C176 200 336 200 336 288V400"/></g>`;
const svg = (body) => Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">${body}</svg>`);
const rounded = (scale) => svg(`<rect width="512" height="512" rx="112" fill="${accent}"/>${glyph(scale)}`);
// Maskable and apple-touch icons are full-bleed squares; the glyph stays inside the 80% safe zone.
const bleed = svg(`<rect width="512" height="512" fill="${accent}"/>${glyph(0.8)}`);

const png = async (source, size, path, opaque = false) => {
  let image = sharp(source, { density: 384 }).resize(size, size);
  if (opaque) image = image.flatten({ background: accent });
  await image.png({ compressionLevel: 9 }).toFile(root(path));
};

mkdirSync(root("public/icons"), { recursive: true });
mkdirSync(root("public/fonts"), { recursive: true });
await png(rounded(1), 192, "public/icons/icon-192.png");
await png(rounded(1), 512, "public/icons/icon-512.png");
await png(bleed, 512, "public/icons/icon-maskable-512.png", true);
await png(bleed, 180, "public/icons/apple-touch-icon.png", true);
await png(rounded(1), 32, "public/favicon-32.png");
writeFileSync(root("public/favicon.svg"), rounded(1));

// Fonts for the offline page (the app itself loads them through next/font with hashed names).
for (const font of ["Inter-latin-variable.woff2", "JetBrainsMono-latin-variable.woff2"]) copyFileSync(root(`app/fonts/${font}`), root(`public/fonts/${font}`));

// Offline page: all five themes by the same tokens; the inline script is the app's own theme init.
const offlineCss = `/* GENERATED by scripts/generate-pwa-assets.mjs from app/styles/tokens.css and scripts/pwa/offline.css. Do not edit. */\n${tokens}\n${readFileSync(root("scripts/pwa/offline.css"), "utf8")}`;
writeFileSync(root("public/offline.css"), offlineCss);
const html = readFileSync(root("scripts/pwa/offline.template.html"), "utf8").replace("/*THEME_INIT*/", () => themeInitScript).replace("/*THEME_COLOR*/", MANIFEST_THEME_COLOR);
writeFileSync(root("public/offline.html"), html);
console.log("PWA assets written to public/");
